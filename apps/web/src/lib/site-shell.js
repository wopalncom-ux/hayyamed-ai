/**
 * Open Graph block for an individual page. A page-level `openGraph` replaces
 * the root one entirely, so this re-adds the shared fields (site name,
 * locale and the alternate locale) every page needs.
 */
export function pageOpenGraph(locale, { title, description, url, type = 'website' }) {
  const c = COPY[locale] || COPY.en
  return { type, siteName: 'Hayya AI', locale: c.ogLocale, alternateLocale: c.ogAlt, title, description, url }
}
