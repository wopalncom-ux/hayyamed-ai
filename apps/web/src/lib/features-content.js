/** Feature content in the given locale (falls back to English). */
export function getFeature(slug, locale = 'en') {
  const base = getFeatureContent(slug)
  if (!base) return undefined
  if (locale !== 'ar' || !FEATURES_AR[slug]) return base
  return { ...base, ...FEATURES_AR[slug] }
}

/** All features in the given locale. */
export function getFeatures(locale = 'en') {
  return FEATURES_CONTENT.map((f) => getFeature(f.slug, locale))
}
